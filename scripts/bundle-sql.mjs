// Combines supabase/migrations/*.sql into one file per phase, to paste into the
// Supabase SQL Editor. Each migration belongs to the latest phase that starts at
// or before its timestamp.
// Usage: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";

const PHASES = [
  { name: "phase1", starts: "20261029130000", title: "Phase 1 database (tables + row-level security)" },
  { name: "phase2", starts: "20261029140000", title: "Phase 2 database changes (quiz bank import)" },
  { name: "phase3", starts: "20261029150000", title: "Phase 3 database changes (interview, gray cards, uploads)" },
  {
    name: "phase2b",
    starts: "20261029160000",
    title: "Phase 2b database changes (SPEC v2 certification engine)",
    after: "phase2.sql (with or without phase3.sql)",
  },
  {
    name: "phase2c",
    starts: "20261029170000",
    title: "Phase 2c database changes (rule tiers, doctor setup flow)",
    after: "phase2b.sql",
  },
  {
    name: "phase2d",
    starts: "20261030120000",
    title: "Phase 2d database changes (suggested answers, bank v2.1)",
    after: "phase2c.sql",
  },
];

const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

for (const [i, phase] of PHASES.entries()) {
  const next = PHASES[i + 1]?.starts ?? "99999999999999";
  const mine = files.filter((f) => f >= phase.starts && f < next);
  if (mine.length === 0) continue;

  const header = `-- VFDA VA Quiz App - ${phase.title}.
-- GENERATED by \`npm run db:bundle\` from supabase/migrations/. Edit those files, not this one.
-- Paste into the Supabase SQL Editor and run${i > 0 ? ` after ${phase.after ?? `${PHASES[i - 1].name}.sql`}` : " once on an empty project"}.
-- Runs in one transaction: if anything fails, nothing is changed.

begin;
`;
  const body = mine
    .map((f) => `\n-- ===== ${f} =====\n\n${readFileSync(join(dir, f), "utf8").trim()}\n`)
    .join("");

  const out = `supabase/${phase.name}.sql`;
  writeFileSync(out, `${header}${body}\ncommit;\n`);
  console.log(`Wrote ${out} from ${mine.length} migration(s): ${mine.join(", ")}`);
}
